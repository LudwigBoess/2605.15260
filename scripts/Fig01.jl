function Fig01(plot_name)

    shapes = [S1, S2, S3, S4, S5, S6, S7, S8, S9, S10, S11]
    x_range = LinRange(-6.0, 6.0, 1_000)

    f = Figure(size=(450, 400))

    ax1 = Axis(f[1, 1], ylabel=L"\mathcal{S}_\mathcal{O}(x)", xlabel=L"x", 
                xminorticks=IntervalsBetween(2), yminorticks=IntervalsBetween(5), xticks = -5:5)
    xlims!(ax1, (-4.0, 4.0))
    ylims!(ax1, (0.0, 1.))
    i = 1

    # particle data
    for S in shapes
        lines!(ax1, x_range, S.(x_range), linewidth = 3.5, color = :white, alpha=0.3)
        lines!(ax1, x_range, S.(x_range), label=L"\mathcal{S}_{%$i}", color = i, colormap = :thermal, colorrange=(0,length(shapes)+1), linewidth=2.5)
        i += 1
    end
    axislegend(ax1, position = :lt, framevisible=false)
    resize_to_layout!(f)
    save(plot_name, f)

end

